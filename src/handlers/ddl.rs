    #[test]
    fn refuses_referential_actions_db2_does_not_have() {
        let build = |on_delete, on_update| {
            get_create_foreign_key_sql("O", "FK", "U", "P", "ID", on_delete, on_update, None)
        };
        assert_eq!(
            build(None, Some("CASCADE")).unwrap_err(),
            "Db2 does not support ON UPDATE CASCADE; use NO ACTION, RESTRICT"
        );
        assert!(build(None, Some("SET NULL")).is_err());
        assert!(build(Some("SET DEFAULT"), None).is_err());
        for rule in ["NO ACTION", "RESTRICT", "CASCADE", "SET NULL"] {
            assert!(build(Some(rule), None).is_ok(), "{rule}");
        }
    }

    #[test]
    fn drops_are_quoted() {
        assert_eq!(
            drop_index_sql("T", "idx price", Some("APP")),
            "DROP INDEX \"APP\".\"idx price\""
        );
        assert_eq!(
            drop_foreign_key_sql("Order Details", "FK \"x\"", Some("APP")),
            format!("ALTER TABLE {T} DROP FOREIGN KEY \"FK \"\"x\"\"\"")
        );
    }
